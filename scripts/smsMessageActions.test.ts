import assert from "node:assert/strict";
import { latestSmsReply, removeSmsMessages } from "../src/features/sms/smsMessageActions";
import type { SmsMessage, SmsStore, SmsTimeline } from "../src/domain/sms/smsTypes";
const timeline: SmsTimeline = {id:"t",characterId:"c",ownerIdentityId:"u",phoneNumber:"123",label:"",mode:"unanchored",kind:"custom",knowsCurrentTimeline:false,createdAt:1,updatedAt:1};
const message=(id:string,sender:SmsMessage["sender"],receivedAt:number):SmsMessage=>({id,timelineId:"t",characterId:"c",ownerIdentityId:"u",phoneNumber:"123",sender,content:id,receivedAt});
const messages=[message("old-user","user",1),message("old-reply","character",2),message("user","user",3),message("a","character",4),message("b","character",5)];
assert.equal(latestSmsReply(messages,messages[1]),null,"historic replies cannot regenerate");
assert.deepEqual(latestSmsReply(messages,messages[3])?.replies.map(m=>m.id),["a","b"]);
assert.equal(latestSmsReply([...messages,message("new-user","user",6)],messages[4]),null);
assert.equal(latestSmsReply(messages,{...messages[4],ownerIdentityId:"other"}),null);
const other={...messages[4],ownerIdentityId:"other",content:"private"};
const store:SmsStore={version:1,phones:[],timelines:[timeline],messages:[...messages,other],memories:[{timelineId:"t",characterId:"c",ownerIdentityId:"u",phoneNumber:"123",notes:["stale"],relationshipSummary:"stale",updatedAt:1,processedRevisions:{a:"revision",user:"revision"}}]};
const next=removeSmsMessages(store,timeline,["a"]);
assert.ok(next.messages.includes(other),"same message ID in another identity is preserved");
assert.ok(!next.memories[0].notes.some(note=>note.endsWith("：a")));
assert.equal(next.memories[0].relationshipSummary,undefined);
assert.equal(next.memories[0].processedRevisions?.a,undefined);
assert.equal(next.memories[0].processedRevisions?.user,"revision");
assert.equal(store.messages.length,6,"request preparation never mutates original replies");
assert.deepEqual(store.memories[0].notes,["stale"]);
console.log("PASS SMS latest reply scope and source memory invalidation");

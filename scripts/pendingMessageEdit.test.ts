import assert from "node:assert/strict";
import { canEditPendingMessage, isPlainPendingText } from "../src/domain/chat/pendingMessageEdit";
import { createPendingMessageMutationQueue } from "../src/features/chat/services/pendingMessageMutationQueue";
import type { Message } from "../src/types";
const message:Message={id:"pending",characterId:"a",relationId:"r",conversationId:"c",authorIdentityId:"u",sender:"user",content:"今天去书店",timestamp:1,pendingReplyEditable:true};
assert.ok(canEditPendingMessage(message,[message]));
assert.ok(canEditPendingMessage(message,[message,{...message,id:"pending2",timestamp:2}]));
assert.ok(!canEditPendingMessage(message,[{...message,pendingReplyEditable:false}]));
assert.ok(!canEditPendingMessage(message,[{...message,pendingReplyEditable:undefined}]));
assert.ok(!canEditPendingMessage(message,[message,{...message,id:"reply",sender:"character",timestamp:2}]));
assert.ok(canEditPendingMessage(message,[message,{...message,id:"other",sender:"character",relationId:"other",timestamp:2}]));
for(const patch of [{content:"[语音|你好]"},{content:"data:image/png;base64,abc"},{isOffline:true},{recalledAt:2},{callId:"call"},{sender:"character" as const}])assert.ok(!isPlainPendingText({...message,...patch}));
let current={...message};
const queue=createPendingMessageMutationQueue();
let release!:()=>void;
const pause=new Promise<void>(resolve=>release=resolve);
const edit=queue(async()=>{await pause;current={...current,content:"明天去书店"};return true;});
const prepare=queue(()=>{current={...current,pendingReplyEditable:false};return {...current};});
release();await edit;
assert.equal((await prepare).content,"明天去书店","reply snapshot waits for and includes the completed edit");
assert.equal(current.pendingReplyEditable,false,"failed/stopped replies cannot reopen editing");
const denied=await queue(()=>canEditPendingMessage(message,[current]));assert.equal(denied,false);
await assert.rejects(queue(()=>{throw new Error("write failed");}));
assert.equal(await queue(()=>"next"),"next","a failed task does not deadlock later operations");
console.log("PASS pending edit eligibility, scope isolation, durable lock policy and serialized reply snapshot");

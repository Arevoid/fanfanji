import assert from "node:assert/strict";
import {indexedDB} from "fake-indexeddb";
import {readingAssetDb} from "../src/core/storage/readingAssetDb";
import {loadCommittedMessages,saveMessages} from "../src/core/storage/repositories/messageRepository";
import {loadCommittedCoReadingStore,saveCoReadingStore} from "../src/core/storage/repositories/readingCoReadingRepository";
import {createEmptyCoReadingStore} from "../src/domain/reading/coReadingTypes";
const values=new Map<string,string>();const localStorage={getItem:(k:string)=>values.get(k)??null,setItem:(k:string,v:string)=>values.set(k,v),removeItem:(k:string)=>values.delete(k)};
Object.assign(globalThis,{indexedDB,localStorage,window:{localStorage}});
const original=readingAssetDb.saveMetadataValue;let writes=0;
readingAssetDb.saveMetadataValue=async(...args)=>{writes++;return original.apply(readingAssetDb,args);};
await loadCommittedMessages();await loadCommittedCoReadingStore();assert.equal(writes,0,"cold lookup cannot initialize or migrate stores");
const message={id:"saved",characterId:"a",relationId:"r",conversationId:"c",sender:"character" as const,content:"已保存回复",timestamp:Date.now()};
saveMessages([message]);assert.deepEqual((await loadCommittedMessages()).value,[message]);
readingAssetDb.saveMetadataValue=async()=>{throw Error("synthetic failed save");};
saveMessages([{...message,id:"failed",content:"不能当作已说过"}]);
assert.equal((await loadCommittedMessages()).valid,false,"first lookup reports failed durable write");
assert.deepEqual((await loadCommittedMessages()).value,[message],"a consumed writer error cannot turn optimistic cache into durable evidence");
saveCoReadingStore(createEmptyCoReadingStore());assert.equal((await loadCommittedCoReadingStore()).valid,false);
assert.equal((await loadCommittedCoReadingStore()).found,false,"failed initial reading write cannot create committed evidence on the second read");
readingAssetDb.saveMetadataValue=original;
console.log("PASS committed output durability: cold reads never migrate, queued save awaited, failed optimistic snapshots never become evidence after error consumption");

import assert from "node:assert/strict";
import { acceptLifeEpisode, applyLifeContinuation, emptyCharacterContinuity, selectCharacterContinuityContext } from "../src/domain/memory/characterContinuity";
import { projectLifePlans, isLifeExperience } from "../src/domain/memory/lifePlanProjection";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { CharacterLifePlans } from "../src/features/characterKnowledge/components/CharacterLifePlans";
import { CHARACTER_CONTINUITY_KEY } from "../src/core/storage/repositories/characterContinuityRepository";
const scope = { characterId: "a", userIdentityId: "u", relationId: "r", conversationId: "c" };
const now = Date.UTC(2026, 9, 26);
const plan = acceptLifeEpisode({ summary: "准备整理书架", status: "planned" }, scope, now, "plan", [])!;
assert.ok(plan);
const others = [{ ...plan, id: "other-role", characterId: "b" }, { ...plan, id: "other-user", userIdentityId: "v" }];
assert.deepEqual(projectLifePlans([plan, ...others], "u", "a"), [plan]);
assert.equal(projectLifePlans([plan], "u", "a")[0].scheduleSlot, undefined, "no invented date");
assert.equal(isLifeExperience(plan), false);
const done = applyLifeContinuation([plan], { previousEpisodeId: plan.id, summary: "整理好了书架", status: "completed" }, scope, now + 1000, "done", []);
assert.equal(done.length, 2);
assert.equal(projectLifePlans(done, "u", "a").length, 0, "completion removes the same plan from both schedule views");
assert.deepEqual(done.filter(isLifeExperience).map(item => item.id), ["done"]);
assert.equal(isLifeExperience({ ...done[1], experienceAssessed: true }), false, "routine progress stays internal without meaningful impact");
assert.equal(projectLifePlans([{ ...plan, status: "cancelled" }], "u", "a").length, 0);
assert.equal(projectLifePlans([{ ...plan, supersededById: "rescheduled" }, { ...plan, id: "rescheduled", summary: "下周再整理书架" }], "u", "a").length, 1);
assert.match(selectCharacterContinuityContext({ ...emptyCharacterContinuity(), life: [plan] }, scope, [], "最近生活", now, 2000), /准备整理书架/, "moving UI does not remove the plan from character context");
const values = new Map([[CHARACTER_CONTINUITY_KEY, JSON.stringify({ ...emptyCharacterContinuity(), life: [plan, ...others] })]]);
Object.defineProperty(globalThis, "window", { configurable: true, value: { localStorage: { getItem: (key: string) => values.get(key) ?? null } } });
const html = renderToStaticMarkup(createElement(CharacterLifePlans, { userIdentityId: "u", characterId: "a" }));
assert.match(html, /生活计划/); assert.match(html, /时间待定/);
assert.equal((html.match(/准备整理书架/g) || []).length, 1);
values.set(CHARACTER_CONTINUITY_KEY, JSON.stringify({ ...emptyCharacterContinuity(), life: done }));
assert.equal(renderToStaticMarkup(createElement(CharacterLifePlans, { userIdentityId: "u", characterId: "a" })), "");
delete (globalThis as { window?: unknown }).window;
console.log("life plans schedule projection passed");
